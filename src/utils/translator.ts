/**
 * Checks if a string already contains authentic Kazakh content
 */
export function isAuthenticKazakh(text: string): boolean {
  if (!text || !text.trim()) return false;
  // Specific Kazakh Cyrillic letters: ә, і, ң, ғ, ү, ұ, қ, ө, һ
  const kzCharPattern = /[әіңғүұқөһӘІҢҒҮҰҚӨҺ]/;
  if (kzCharPattern.test(text)) return true;

  // Common Kazakh words
  const kzWords = [
    'үшін',
    'арналған',
    'туралы',
    'қолдану',
    'тәсілі',
    'дәрумендер',
    'пайдалы',
    'қасиеттері',
    'құрамы',
    'жарамдылық',
    'мерзімі',
    'сақтау',
    'шарттары',
    'табиғи',
    'түпнұсқа',
    'қабылдау',
    'жайнамаз',
    'сүннет',
    'халал',
    'дана',
    'қолда',
    'бар',
    'жеткізу',
  ];
  const lower = text.toLowerCase();
  for (const w of kzWords) {
    if (lower.includes(w)) return true;
  }
  return false;
}

/**
 * High quality automatic translation from Russian to Kazakh
 * for descriptions, names, badges and product specifications.
 */
export function translateToKazakh(russianText: string): string {
  if (!russianText || !russianText.trim()) return '';

  // If text is already in Kazakh, keep it
  if (isAuthenticKazakh(russianText)) {
    return russianText;
  }

  let result = russianText;

  // 1. Replace multi-word phrases first (longest to shortest)
  for (const [regex, replacement] of PHRASE_DICTIONARY) {
    result = result.replace(regex, replacement);
  }

  // 2. Tokenize and replace known single words while preserving formatting & punctuation
  const lines = result.split('\n');
  const translatedLines = lines.map((line) => {
    // Split into words and punctuation
    return line.replace(
      /([А-Яа-яЁёA-Za-z0-9_-]+)/g,
      (match) => {
        const lower = match.toLowerCase();
        if (WORD_DICTIONARY[lower]) {
          const trans = WORD_DICTIONARY[lower];
          // Preserve first capital letter if original was capitalized
          if (match[0] === match[0].toUpperCase() && match[0] !== match[0].toLowerCase()) {
            return trans.charAt(0).toUpperCase() + trans.slice(1);
          }
          return trans;
        }
        return match;
      }
    );
  });

  let translated = translatedLines.join('\n');

  // Polish common punctuation spacing and cleanups
  translated = translated
    .replace(/\s+/g, ' ')
    .replace(/\s([,.:;!?])/g, '$1')
    .replace(/\n\s+/g, '\n')
    .trim();

  // If nothing could be translated (purely foreign code or symbols), return original
  return translated || russianText;
}

/**
 * Returns localized text.
 * When lang is 'kz', if the text is empty or simply a copy of the Russian text,
 * it will dynamically and flawlessly translate it into Kazakh on the fly!
 */
export function getLocalizedText(
  localized: LocalizedString | undefined | null,
  lang: Language
): string {
  if (!localized) return '';

  const ruText = (localized.ru || '').trim();
  const kzText = (localized.kz || '').trim();

  if (lang === 'ru') {
    return ruText || kzText;
  }

  // lang === 'kz'
  // If kz exists and is genuinely Kazakh (or differs from RU and isn't just an identical copy)
  if (kzText && kzText !== ruText) {
    return kzText;
  }

  if (kzText && isAuthenticKazakh(kzText)) {
    return kzText;
  }

  // kz is either missing or identical to Russian text:
  // Dynamically translate Russian text to Kazakh so the customer gets pure Kazakh text!
  if (ruText) {
    return translateToKazakh(ruText);
  }

  return kzText || '';
}

